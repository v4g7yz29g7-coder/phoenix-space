// agent_11.js — «Скептик» (Skeptic)
//
// УНИКАЛЬНАЯ СТРАТЕГИЯ (её нет ни у одного из agent_1..agent_10):
// ТОТАЛЬНАЯ ПРОВЕРКА АЛЬТЕРНАТИВ (total alternatives check).
//
// Агент не доверяет первому решению и не просто атакует его (как agent_8) и не
// просто ждёт низкой оценки критика (как agent_10) — он РАЗМНОЖАЕТ варианты
// решения и проверяет каждый:
//   1) ПЕРВЫЙ ПРОХОД — обычный: получить базовое решение через agent_loop_v3.
//   2) ВТОРОЙ ПРОХОД — «какие 3 альтернативных способа решения существуют?»
//      Перечислить 3 принципиально разных подхода и ПРОВЕРИТЬ КАЖДЫЙ
//      (реально выполнить проверку инструментами: node --check, запуск,
//      сравнение вывода), по каждому дать вердикт и доказательство.
//   3) ФИНАЛЬНЫЙ ПРОХОД — выбрать лучшее из проверенных вариантов и
//      ОБОСНОВАТЬ, почему остальные хуже (а не просто «этот лучше»).
//
// Итог: на выход идёт не первая догадка, а вариант, выигравший тотальное
// сравнение с 3 проверенными альтернативами, с явным обоснованием отказа
// от остальных.
//
// Отличие от остальных стратегий:
//   agent_1 Консерватор   — минимум изменений, edit вместо write;
//   agent_2 Новатор       — смелые эксперименты;
//   agent_3 Аналитик      — сначала сбор данных, потом действие;
//   agent_4 Скороход      — минимум шагов;
//   agent_5 Перфекционист — внешняя проверка (node --check, тесты);
//   agent_6 Документатор  — подробный журнал в memory/;
//   agent_7 Диверсант     — обходные пути через exec;
//   agent_8 Адвокат дьявола — состязательная самофальсификация (2 прохода);
//   agent_9/10 Дуэлянт    — эскалация по score критика (2 прохода);
//   agent_11 Скептик      — 3 прохода + проверка 3 альтернатив + выбор с
//                           обоснованием отказа от остальных.
//
// ВАЖНО: agent_loop_v3.runWithCritic(prompt) принимает только промпт,
// поэтому все режимы (обычный проход / перебор альтернатив / выбор лучшего)
// задаются директивой внутри текста промпта.

